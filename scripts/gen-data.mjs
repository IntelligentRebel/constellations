// Generates typed data modules from the research JSON (craig-stars MIT data extraction).
import fs from 'node:fs';
// R: folder of the JSON extracted from craig-stars (https://github.com/sirgwain/craig-stars); not part of this repository
const R = process.env.CRAIG_DATA || '../craig-stars/data/';
const out = 'src/data/';
const techs = JSON.parse(fs.readFileSync(R + 'techs.json', 'utf8')).techs;
const hulls = JSON.parse(fs.readFileSync(R + 'hulls.json', 'utf8')).hulls;
const traits = JSON.parse(fs.readFileSync(R + 'prt_lrt.json', 'utf8'));
const rules = JSON.parse(fs.readFileSync(R + 'rules.json', 'utf8'));

const reqOf = (r) => {
  const o = { en: r.energy, we: r.weapons, pr: r.propulsion, co: r.construction, el: r.electronics, bi: r.biotechnology };
  for (const k of ['prtsRequired', 'prtsDenied', 'lrtsRequired', 'lrtsDenied', 'hullsAllowed', 'hullsDenied']) if (r[k] && r[k].length) o[k] = r[k];
  if (r.acquirable) o.acquirable = true;
  return o;
};
const costOf = (c) => [c.ironium || 0, c.boranium || 0, c.germanium || 0, c.resources || 0];

const T = techs.filter(t => t.category !== 'ShipHull' && t.category !== 'StarbaseHull').map(t => {
  const o = { name: t.name, cat: t.category, tags: t.tags, req: reqOf(t.requirements), cost: costOf(t.cost), rank: t.ranking || 0 };
  if (t.origin) o.origin = t.origin;
  if (t.mass !== undefined) o.mass = t.mass;
  if (t.hullSlotType) o.slot = t.hullSlotType;
  const s = { ...(t.stats || {}) };
  delete s.scanner;
  if (Object.keys(s).length) o.stats = s;
  if (t.engine) o.engine = { ideal: t.engine.idealSpeed, free: t.engine.freeSpeed, maxSafe: t.engine.maxSafeSpeed, fuel: t.engine.fuelUsage, scoop: !!t.engine.ramscoop, radiating: !!t.engine.radiating };
  return o;
});
const H = hulls.map(h => {
  const o = {
    name: h.name, type: h.type, starbase: !!h.starbase, req: reqOf(h.requirements), cost: costOf(h.cost), rank: h.ranking || 0,
    mass: h.mass, armor: h.armor, fuel: h.fuelCapacity, cargo: h.cargoCapacity, init: h.initiative,
    slots: h.slots.map(s => ({ types: s.types, cap: s.capacity, req: !!s.required, x: s.position.x, y: s.position.y })),
  };
  if (h.origin) o.origin = h.origin;
  if (h.fuelGeneration) o.fuelGen = h.fuelGeneration;
  if (h.spaceDock) o.dock = h.spaceDockUnlimited ? -1 : h.spaceDock;
  if (h.mineLayingBonus) o.mineLayingBonus = h.mineLayingBonus;
  if (h.repairBonus) o.repairBonus = h.repairBonus;
  if (h.immuneToOwnDetonation) o.immuneToOwnDetonation = true;
  if (h.rangeBonus) o.rangeBonus = h.rangeBonus;
  if (h.builtInScanner) o.builtInScanner = true;
  if (h.doubleMineEfficiency) o.doubleMineEfficiency = true;
  if (h.maxPopulation) o.maxPop = h.maxPopulation;
  if (h.innateScanRangePenFactor) o.innatePenFactor = h.innateScanRangePenFactor;
  if (h.orbitalConstructionHull) o.orbitalConstruction = true;
  if (h.cargoCapacity) o.cargoBox = { x: h.cargoSlotPosition.x, y: h.cargoSlotPosition.y, w: h.cargoSlotSize.x, h: h.cargoSlotSize.y, circle: !!h.cargoSlotCircle };
  if (h.spaceDock) o.dockBox = { x: h.spaceDockSlotPosition.x, y: h.spaceDockSlotPosition.y, w: h.spaceDockSlotSize.x, h: h.spaceDockSlotSize.y, circle: !!h.spaceDockSlotCircle };
  return o;
});
const head = '// AUTO-GENERATED by scripts/gen-data.mjs from Stars! data tables (via craig-stars, MIT). Do not edit.\n';
fs.writeFileSync(out + 'techs.ts', head + "import type { TechData } from './types';\nexport const TECH_DATA: TechData[] = " + JSON.stringify(T, null, 0).replace(/\},\{"name"/g, '},\n{"name"') + ';\n');
fs.writeFileSync(out + 'hulls.ts', head + "import type { HullData } from './types';\nexport const HULL_DATA: HullData[] = " + JSON.stringify(H, null, 0).replace(/\},\{"name"/g, '},\n{"name"') + ';\n');
// traits
const prts = traits.prts.map(p => ({ code: p.code, name: p.name, desc: p.uiDescription, spec: p.spec }));
const lrts = traits.lrts.map(l => ({ code: l.code, name: l.name, desc: l.uiDescription, points: l.advantagePoints, spec: l.spec }));
fs.writeFileSync(out + 'traits-raw.ts', head + 'export const PRT_RAW: any[] = ' + JSON.stringify(prts, null, 1) + ';\nexport const LRT_RAW: any[] = ' + JSON.stringify(lrts, null, 1) + ';\nexport const DEFAULT_PRT_SPEC: any = ' + JSON.stringify(traits.defaultPRTSpec, null, 1) + ';\n');
const rr = rules.rules;
const keep = {
  cloakTable: rules.cloakPercentByCloakUnits.table,
  movesPerRound: rules.battle.movesPerRoundBlock,
  battleStart: rules.battle.startingPositionsByPlayerIndex,
  minefieldStats: rr.minefieldStatsByType,
  wormholeStats: rr.wormholeStatsByStability,
  cometStats: rr.cometStatsBySize,
  mysteryTrader: rr.mysteryTraderRules,
  mtDesigns: rules.mysteryTrader.designs,
  mtTechs: rules.mysteryTrader.MysteryTraderTechs,
  universeSizes: rules.universe.sizes,
  techBaseCost: rr.techBaseCost,
};
fs.writeFileSync(out + 'rules-raw.ts', head + 'export const RULES_RAW: any = ' + JSON.stringify(keep, null, 0) + ';\n');
console.log('techs', T.length, 'hulls', H.length);
